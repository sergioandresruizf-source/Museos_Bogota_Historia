// Homenaje al campesino colombiano
// BONITO: sale en la placa oficial.  VISCERAL: sale cuando se termina de romper la obra.
GUION(`
BONITO:
Magnífico mural en honor al hombre del campo, base de nuestra patria, integrado armoniosamente a la arquitectura con un práctico acceso.

VISCERAL:
Qué homenaje tan berraco: le abrieron una puerta en toda la mitad. Así quieren al campesino, pintado en la pared y quitado cuando estorba para pasar. Descascarado, mutilado y con baldes al pie. Le aplauden la ruana en campaña y le niegan la tierra, la vía y el crédito. Se les cae el mural y se les cae la cara.
`);
