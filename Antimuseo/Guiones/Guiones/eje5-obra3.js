// Monumento a los héroes
// BONITO: sale en la placa oficial.  VISCERAL: sale cuando se termina de romper la obra.
GUION(`
BONITO:
Imponente monumento a las gestas libertadoras, con los nombres de las gloriosas batallas grabados en piedra. Manténgase limpio en memoria de nuestros héroes.

VISCERAL:
ENEMIGO PÚBLICO, en letras bien grandes, para que lo lea hasta el que no quiere. La gente le pintó encima a la piedra lo que la piedra callaba. Y ahí sí saltaron los indignados: que el patrimonio, que la limpieza. Les duele más un muro rayado que un pelado tendido en el andén. El monumento ya lo tumbaron. La rabia no.
`);
